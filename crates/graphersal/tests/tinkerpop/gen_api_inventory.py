#!/usr/bin/env python3
"""Regenerates `api-<tag>.txt`, the TinkerPop API inventory used by the feature-suite harness.

Usage (see README.md, "API inventory"):

    python3 gen_api_inventory.py <tinkerpop checkout> <tag> <commit> > api-<tag>.txt

Sources (Apache-2.0, Apache TinkerPop):
  - gremlin-language/src/main/antlr4/Gremlin.g4 — the canonical Gremlin grammar. It is the
    authority for the `GraphTraversalSource`, `GraphTraversal`, terminal and token sections.
  - gremlin-core/.../dsl/graph/__.java — the `__` section (public static methods).

The grammar is read with a few regular expressions, not a full ANTLR parser: every entry is the
first keyword token (`K_*`) of a rule alternative, resolved to its literal through the lexer rules
(`K_ADDV: 'addV';`). Token members are the `K_<CLASS> DOT K_<MEMBER>` pairs.
"""

import re
import sys
from pathlib import Path

GRAMMAR = "gremlin-language/src/main/antlr4/Gremlin.g4"
ANON = "gremlin-core/src/main/java/org/apache/tinkerpop/gremlin/process/traversal/dsl/graph/__.java"


def rules(text):
    """Parser rules: name -> body (text between ':' and the terminating ';')."""
    # Drop comments first.
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    out = {}
    for m in re.finditer(r"^[ \t]*([a-zA-Z_][a-zA-Z0-9_]*)\s*\n?\s*:(.*?)^\s*;", text, flags=re.S | re.M):
        out[m.group(1)] = m.group(2)
    return out


def lexer_literals(text):
    """Lexer keyword rules: `K_ADDV: 'addV';` -> {'K_ADDV': 'addV'}."""
    return dict(re.findall(r"^(K_[A-Z0-9_]+)\s*:\s*'([^']+)'\s*;", text, flags=re.M))


def alternatives(body):
    """Top-level alternatives of a rule body (labels `#name` removed)."""
    body = re.sub(r"#\s*\w+", "", body)
    return [a.strip() for a in body.split("|")]


def first_keywords(body):
    """The first `K_*` token of every alternative that starts with one."""
    out = []
    for alt in alternatives(body):
        m = re.match(r"\(?\s*(K_[A-Z0-9_]+)", alt)
        if m:
            out.append(m.group(1))
    return out


def referenced_rules(body, prefix):
    return re.findall(r"\b(" + re.escape(prefix) + r"\w*)\b", body)


def main():
    root, tag, commit = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    grammar = (root / GRAMMAR).read_text()
    rs = rules(grammar)
    lit = lexer_literals(grammar)

    def names(rule_names):
        found = set()
        for r in rule_names:
            for k in first_keywords(rs[r]):
                found.add(lit[k])
        return found

    source = names(referenced_rules(rs["traversalSourceSelfMethod"], "traversalSourceSelfMethod_"))
    source |= names(referenced_rules(rs["traversalSourceSpawnMethod"], "traversalSourceSpawnMethod_"))
    # `g.tx()` (transactionPart).
    source |= {lit[k] for k in re.findall(r"^\s*(K_[A-Z]+)", rs["transactionPart"], flags=re.M)[:1]}
    steps = names(referenced_rules(rs["traversalMethod"], "traversalMethod_"))
    terminal = names(referenced_rules(rs["traversalTerminalMethod"], "traversalTerminalMethod_"))

    # Token classes: `K_<CLASS> DOT K_<MEMBER>` and `<x>StringConstant DOT K_<MEMBER>`.
    string_constants = {
        name: lit[first_keywords(body)[0]]
        for name, body in rs.items()
        if name.endswith("StringConstant")
    }
    tokens = set()
    for body in rs.values():
        for cls, member in re.findall(r"\b(K_[A-Z0-9_]+|\w+StringConstant)\s+DOT\s+(K_[A-Z0-9_]+)", body):
            cls_name = string_constants[cls] if cls in string_constants else lit[cls]
            if cls_name[0].isupper():
                tokens.add(f"{cls_name}.{lit[member]}")

    anon_src = (root / ANON).read_text()
    java_anon = set(re.findall(r"public\s+static\s+(?:<[^>]*(?:<[^>]*>[^>]*)*>\s+)?[\w<>?,\s\[\]]+?\s(\w+)\s*\(", anon_src))
    # The grammar accepts `__.` before any step; `__` lists those that __.java actually declares
    # (so modulators such as `by`/`with`/`option` and the computer steps drop out). The Java-only
    # factories `__.start()` / `__.__(..)` are not part of the canonical language.
    anon = java_anon & steps
    java_only = sorted(java_anon - steps)

    print(f"# Apache TinkerPop {tag} traversal API inventory (commit {commit}).")
    print("# Generated by tests/tinkerpop/gen_api_inventory.py from Gremlin.g4 and __.java (Apache-2.0);")
    print("# do not edit by hand. See tests/tinkerpop/README.md, section \"API inventory\".")
    print("# One entry per line, sorted within each [section]; token entries are `Class.member`.")
    print(f"# [__] = __.java public static methods that are also grammar steps (left out: {', '.join(java_only)}).")
    for section, entries in [
        ("GraphTraversalSource", source),
        ("GraphTraversal", steps),
        ("__", anon),
        ("terminal", terminal),
        ("tokens", tokens),
    ]:
        print()
        print(f"[{section}]")
        for e in sorted(entries):
            print(e)


if __name__ == "__main__":
    main()
